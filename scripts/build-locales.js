#!/usr/bin/env node
'use strict';

/*
 * Locale source of truth: locales/<code>.json.
 * Browsers from file:// cannot fetch JSON, and WeChat mini programs are happier
 * with a CommonJS module, so this script emits one generated JS bundle.
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const CODES = ['zh-CN', 'zh-Hant', 'en', 'ja', 'fr', 'es'];
const locales = {};
let referenceKeys = null;
let referencePlaceholders = null;
let failures = 0;

function placeholders(text) {
  return Array.from(new Set(Array.from(text.matchAll(/\{([a-zA-Z0-9_]+)\}/g), (match) => match[1]))).sort().join('|');
}

for (const code of CODES) {
  const file = path.join(ROOT, 'src/locales', code + '.json');
  const data = JSON.parse(fs.readFileSync(file, 'utf8'));
  const keys = Object.keys(data).sort();
  if (!referenceKeys) {
    referenceKeys = keys;
    referencePlaceholders = keys.map((key) => placeholders(data[key]));
  } else {
    if (keys.join('|') !== referenceKeys.join('|')) {
      const missing = referenceKeys.filter((key) => !(key in data));
      const extra = keys.filter((key) => !referenceKeys.includes(key));
      console.error(code, 'key mismatch', { missing, extra });
      failures++;
    }
    for (let i = 0; i < referenceKeys.length; i++) {
      if (placeholders(data[referenceKeys[i]]) !== referencePlaceholders[i]) {
        console.error(code, 'placeholder mismatch in', referenceKeys[i]);
        failures++;
      }
    }
  }
  locales[code] = data;
}
if (failures) process.exit(1);

const output = `/*
 * AUTO-GENERATED by scripts/build-locales.js from src/locales/*.json.
 * Do not edit this file; edit the language JSON files and rebuild.
 */
(function (root, factory) {
  if (typeof module === 'object' && module.exports) module.exports = factory();
  else root.SudokuLocales = factory();
})(typeof globalThis !== 'undefined' ? globalThis : this, function () {
  'use strict';
  return ${JSON.stringify(locales, null, 2)};
});
`;

fs.writeFileSync(path.join(ROOT, 'src/ui/locales-data.js'), output);
console.log('Generated src/ui/locales-data.js from', CODES.length, 'locale files.');
